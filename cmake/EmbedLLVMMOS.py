#!/usr/bin/env python3
import sys
import os

if len(sys.argv) < 5:
    print("Usage: python EmbedLLVMMOS.py <llvm_mos_root> <linker_dir> <libs_dir> <out_header>")
    sys.exit(1)

llvm_mos_root = sys.argv[1]
linker_dir = sys.argv[2]
libs_dir = sys.argv[3]
out_header = sys.argv[4]

embed_dirs = {
    linker_dir: "Linker",
    libs_dir: "include/Libs"
}

if llvm_mos_root and os.path.exists(llvm_mos_root):
    common_platform = os.path.join(llvm_mos_root, "mos-platform", "common")
    if os.path.exists(common_platform):
        embed_dirs[common_platform] = "mos-platform/common"

files_to_process = []

for physical_dir, virtual_prefix in embed_dirs.items():
    if not os.path.exists(physical_dir):
        continue
    for root, _, files in os.walk(physical_dir):
        for f in files:
            full_path = os.path.join(root, f)
            rel_path = os.path.relpath(full_path, physical_dir)
            virtual_path = f"{virtual_prefix}/{rel_path}".replace('\\', '/')
            files_to_process.append((full_path, virtual_path))

out = []
out.append("#pragma once\n")
out.append("#include <vector>\n")
out.append("#include <string>\n")
out.append("#include <map>\n")
out.append("#include <cstdint>\n\n")
out.append("// Auto-generated by cmake/EmbedLLVMMOS.py\n")
out.append("static const std::map<std::string, std::vector<uint8_t>> embedded_llvm_mos_files = {\n")

for full_path, vpath in files_to_process:
    try:
        with open(full_path, 'rb') as f:
            data = f.read()
    except Exception:
        continue
    
    out.append(f'  {{"{vpath}", {{\n')
    chunk_size = 32
    for i in range(0, len(data), chunk_size):
        chunk = data[i:i+chunk_size]
        hex_str = ", ".join([f"0x{b:02x}" for b in chunk])
        out.append(f"    {hex_str},\n")
    out.append("  }},\n")

out.append("};\n")

os.makedirs(os.path.dirname(os.path.abspath(out_header)), exist_ok=True)
with open(out_header, 'w') as f:
    f.writelines(out)

print(f"Generated {out_header} with {len(files_to_process)} embedded files.")

