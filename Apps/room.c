typedef struct {
    uint8_t id;
    int16_t z_depth;
} RenderFace;

static RenderFace visible_faces[FACE_OBJ_COUNT];

void rotate_all(uint8_t ax, uint8_t ay, int8_t y_cam) {
    int8_t sin_y = ISIN(ay);
    int8_t cos_y = ICOS(ay);
    int8_t sin_x = ISIN(ax);
    int8_t cos_x = ICOS(ax);

    for (int8_t i = 0; i < NUM_VERTICES; ++i) {
        int16_t x = cvx[i];
        int16_t y = (int16_t)(cvy[i] - y_cam);
        int16_t z = cvz[i];

        int16_t tx = (int16_t)(((x * cos_y) + (z * sin_y)) / 128);
        int16_t tz = (int16_t)(((-x * sin_y) + (z * cos_y)) / 128);

        int16_t ty = (int16_t)(((y * cos_x) - (tz * sin_x)) / 128);
        int16_t tz2 = (int16_t)(((y * sin_x) + (tz * cos_x)) / 128);

        vx[i] = (int8_t)tx;
        vy[i] = (int8_t)ty;
        vz[i] = (int8_t)tz2;
    }
}

void project_all(void) {
    const int16_t distance = 160;
    const int8_t factor = 110;

    for (int8_t i = 0; i < NUM_VERTICES; ++i) {
        int16_t z_shifted = vz[i] + distance;
        if (z_shifted < 5) {
            z_shifted = 5;
        }

        int16_t factor_precalc = (int16_t)(vx[i] * factor);
        px[i] = (int16_t)((factor_precalc / z_shifted) + (GPU_WIDTH / 2));

        factor_precalc = (int16_t)(vy[i] * factor);
        py[i] = (int16_t)((GPU_HEIGHT / 2) - (factor_precalc / z_shifted));
    }
}

void init_graphics(void) {
    lcd_init();
    gpu_fill_screen(0x00U);
}

static inline int32_t calc_face_cross(uint8_t f) {
    uint8_t p1 = faces[f][0];
    uint8_t p2 = faces[f][1];
    uint8_t p3 = faces[f][2];
    int16_t v1x = (int16_t)(px[p2] - px[p1]);
    int16_t v1y = (int16_t)(py[p2] - py[p1]);
    int16_t v2x = (int16_t)(px[p3] - px[p1]);
    int16_t v2y = (int16_t)(py[p3] - py[p1]);
    return ((int32_t)v1x * v2y) - ((int32_t)v1y * v2x);
}

__attribute__((noinline))
static void draw_static_faces(int8_t start, int8_t count, const uint8_t* colors, bool enable_tex) {
    for (int8_t i = start; i < start + count; ++i) {
        if (calc_face_cross((uint8_t)i) >= 0) {
            uint8_t p1 = faces[i][0];
            uint8_t p2 = faces[i][1];
            uint8_t p3 = faces[i][2];
            if (enable_tex && i < FACE_ROOM_COUNT && i != 4 && i != 5) {
                const uint8_t* tex = (i == 2 || i == 3) ? tex_tuff_bricks : tex_copper_bulb;
                const uint8_t* uv = room_uvs[i];
                gpu_draw_tri_tex16(px[p1], py[p1], uv[0], uv[1],
                                   px[p2], py[p2], uv[2], uv[3],
                                   px[p3], py[p3], uv[4], uv[5],
                                   tex);
            } else {
                gpu_draw_tri(px[p1], py[p1], px[p2], py[p2], px[p3], py[p3],
                             colors[i], true);
            }
        }
    }
}

__attribute__((noinline))
static void draw_objects(const uint8_t* active_colors, bool enable_tex) {
    int8_t count = 0;
    for (int8_t i = FACE_OBJ_START; i < FACE_OBJ_START + FACE_OBJ_COUNT; ++i) {
        if (calc_face_cross((uint8_t)i) >= 0) {
            uint8_t p1 = faces[i][0];
            uint8_t p2 = faces[i][1];
            uint8_t p3 = faces[i][2];
            visible_faces[count].id = (uint8_t)i;
            visible_faces[count].z_depth = (int16_t)(vz[p1] + vz[p2] + vz[p3]);
            count++;
        }
    }

    for (int8_t i = 1; i < count; ++i) {
        RenderFace temp_face = visible_faces[i];
        int8_t j_sort = i - 1;

        while (j_sort >= 0 &&
               visible_faces[j_sort].z_depth < temp_face.z_depth) {
            visible_faces[j_sort + 1] = visible_faces[j_sort];
            j_sort--;
        }
        visible_faces[j_sort + 1] = temp_face;
    }

    for (int8_t i = 0; i < count; ++i) {
        uint8_t f = visible_faces[i].id;
        uint8_t p1 = faces[f][0];
        uint8_t p2 = faces[f][1];
        uint8_t p3 = faces[f][2];

        if (enable_tex && ((f >= 25 && f <= 34) || (f >= 37 && f <= 42))) {
            uint8_t u0 = 0, v0 = 15;
            uint8_t u1, v1, u2, v2;
            const uint8_t* tex;
            if (f >= 39) {
                u1 = 8; v1 = 0; u2 = 15; v2 = 15;
                tex = tex_oxidized_copper;
            } else {
                bool is_tri2 = (f <= 34) ? (((f - 25) & 1U) != 0) : (f == 38);
                u1 = 15; v1 = (uint8_t)(is_tri2 ? 0 : 15);
                u2 = (uint8_t)(is_tri2 ? 0 : 15); v2 = 0;
                tex = (f <= 34) ? ((f >= 33) ? tex_grass_top : tex_grass_side) : tex_oxidized_copper;
            }
            gpu_draw_tri_tex16(px[p1], py[p1], u0, v0,
                               px[p2], py[p2], u1, v1,
                               px[p3], py[p3], u2, v2,
                               tex);
        } else {
            gpu_draw_tri(px[p1], py[p1], px[p2], py[p2], px[p3], py[p3],
                         active_colors[f], true);
        }
    }
}

int main(void) {
    uint8_t ang_y = 0;
    bool enable_light = true;
    bool enable_occlusion = true;
    bool enable_tex = false;

    if (arg_count > 1 && _args_ptr != NULL) {
        char** args = _args_ptr;
        for (uint8_t a = 1; a < arg_count; ++a) {
            if (args[a] != NULL) {
                if (strcmp(args[a], "-no-light") == 0) {
                    enable_light = false;
                } else if (strcmp(args[a], "-no-occlusion") == 0) {
                    enable_occlusion = false;
                } else if (strcmp(args[a], "-plain") == 0 || strcmp(args[a], "-fast") == 0) {
                    enable_light = false;
                    enable_occlusion = false;
                } else if (strcmp(args[a], "-light") == 0) {
                    enable_light = true;
                } else if (strcmp(args[a], "-occlusion") == 0) {
                    enable_occlusion = true;
                } else if (strcmp(args[a], "-tex") == 0) {
                    enable_tex = true;
                }
            }
        }
    }

    const uint8_t* active_colors;
    if (enable_light && enable_occlusion) {
        active_colors = face_colors_light_occlusion;
    } else if (enable_light) {
        active_colors = face_colors_light;
    } else if (enable_occlusion) {
        active_colors = face_colors_occlusion;
    } else {
        active_colors = face_colors_default;
    }

    init_graphics();
    lcd_print("Room 3D");
    println("Ctrl + C to exit");

    while (true) {
        if (bios_getchar_nb() == 3) {
            break;
        }

        ang_y = (uint8_t)(ang_y + 1U);

        rotate_all(228, ang_y, 40);
        project_all();

        gpu_fill_screen(0x00U);

        draw_static_faces(FACE_ROOM_START, FACE_ROOM_COUNT, active_colors, enable_tex);

        if (enable_occlusion) {
            draw_static_faces(FACE_AO_START, FACE_AO_COUNT, active_colors, false);
        }

        if (enable_light) {
            draw_static_faces(FACE_SHADOW_START, FACE_SHADOW_COUNT, active_colors, false);
        }

        draw_objects(active_colors, enable_tex);

        drawFrame();
    }
    return 0;
}

