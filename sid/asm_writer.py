import os
import subprocess
import sys

_SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
if _SCRIPT_DIR not in sys.path:
    sys.path.insert(0, _SCRIPT_DIR)

from sid_codec import encode_semantic_v2, decode_semantic_v2, compress_sidlz, decompress_sidlz, verify_lossless


def _split_semantic_stream(sem, max_unpack=17408):
    if len(sem) <= max_unpack:
        return sem, bytearray()
    i = 0
    n = len(sem)
    last_cut = 0
    while i < n:
        cut = i
        if cut > max_unpack:
            break
        last_cut = cut
        cmd = sem[i]
        i += 1
        if cmd == 0xFF:
            break
        elif cmd <= 0x18:
            i += 1
        elif 0x19 <= cmd <= 0x1B:
            i += 2
        elif 0x1C <= cmd <= 0x1E:
            i += 1
        elif 0x1F <= cmd <= 0x21:
            i += 3
        elif 0x22 <= cmd <= 0x2A:
            pass
        elif 0x2B <= cmd <= 0x30:
            i += 2
        elif 0x31 <= cmd <= 0x33:
            i += 1
        elif cmd == 0x34:
            i += 1
        elif cmd == 0x35:
            i += 2
        elif 0x80 <= cmd <= 0xFE:
            pass
        else:
            break
    return sem[:last_cut], sem[last_cut:]


def write_asm(bytecode, input_path, mode, system="NTSC", verify=True):
    """
    Writes a 65C02 assembly ROM player with compressed SIDLZ data extracted to RAM.

    Args:
        bytecode: list of integer byte values (IR v1)
        input_path: original MIDI/NSF file path
        mode: optimization mode string
        system: "NTSC" or "PAL"
        verify: verify lossless roundtrip
    """
    filename_only = os.path.splitext(os.path.basename(input_path))[0].replace(" ", "") + ".s"
    output_dir = os.path.join(_SCRIPT_DIR, "build")
    if not os.path.exists(output_dir):
        os.makedirs(output_dir)
    output_file = os.path.join(output_dir, filename_only)

    print(f"Writing compressed Native ASM to {output_file}...")

    # 1. Encode to Semantic v2
    hdr, sem = encode_semantic_v2(bytecode)

    # 2. Compress with SIDLZ
    # Safe RAM range: $0200 to $45FF = 17408 bytes (avoids SID registers at $4800, ACIA at $5000, VIA at $6000)
    MAX_RAM_UNPACK = 17408
    part1_sem, part2_sem = _split_semantic_stream(sem, MAX_RAM_UNPACK)
    pkg = compress_sidlz(part1_sem)

    if verify:
        p1_rec = decompress_sidlz(pkg, expected_uncompressed_len=len(part1_sem))
        sem_rec = bytearray(p1_rec) + bytearray(part2_sem)
        assert sem_rec == sem, "Semantic stream mismatch in hybrid split"
        ir_rec = decode_semantic_v2(hdr, sem_rec)
        assert ir_rec == bytecode, "Lossless IR mismatch in hybrid split"

    ntbl_first = hdr['ntbl_first']
    ntbl_count = hdr['ntbl_count']
    ntbl = hdr['ntbl']
    dict_delays = hdr['dict']
    pw_step = hdr['pw_step']

    with open(output_file, "w") as f:
        f.write(f"; Generated by audio_to_sid.py (Mode: {mode}, System: {system})\n")
        f.write("; Native 65C02 SIDLZ Compressed ROM Player\n\n")

        f.write(".segment \"ZEROPAGE\"\n")
        f.write("src_ptr:     .res 2\n")
        f.write("dst_ptr:     .res 2\n")
        f.write("play_ptr:    .res 2\n")
        f.write("bit_buf:     .res 1\n")
        f.write("gamma_val:   .res 2\n")
        f.write("zeros_cnt:   .res 1\n")
        f.write("last_off:    .res 2\n")
        f.write("match_off:   .res 2\n")
        f.write("copy_ptr:    .res 2\n")
        f.write("delay_rem:   .res 2\n")
        f.write("temp_reg:    .res 2\n")
        f.write("ctrl_v1:     .res 1\n")
        f.write("ctrl_v2:     .res 1\n")
        f.write("ctrl_v3:     .res 1\n")
        f.write("pw_v1:       .res 2\n")
        f.write("pw_v2:       .res 2\n")
        f.write("pw_v3:       .res 2\n")

        f.write("\n.segment \"CODE\"\n")
        f.write("reset:\n")
        f.write("    ldx #$FF\n    txs\n    cld\n    sei\n\n")

        f.write("    ; Reset SID registers\n")
        f.write("    ldx #$18\n    lda #0\n:   sta $4800, x\n    dex\n    bpl :-\n\n")

        f.write("    ; Init VIA Timer 1 ($6000)\n")
        f.write("    lda #$00\n    sta $600B\n")
        f.write("    lda #$FF\n    sta $6004\n    sta $6005\n    sta $6006\n    sta $6007\n\n")

        f.write("    ; Decompress SIDLZ to RAM ($0200)\n")
        f.write("    lda #<compressed_stream\n    sta src_ptr\n")
        f.write("    lda #>compressed_stream\n    sta src_ptr+1\n")
        f.write("    lda #$00\n    sta dst_ptr\n")
        f.write("    lda #$02\n    sta dst_ptr+1\n")
        f.write("    lda #$80\n    sta bit_buf\n")
        f.write("    stz last_off\n    stz last_off+1\n\n")

        f.write("decomp_loop:\n")
        f.write("    jsr get_bit\n")
        f.write("    bcs @is_match\n\n")

        f.write("    ; Literal run\n")
        f.write("    jsr get_gamma\n")
        f.write("@lit_loop:\n")
        f.write("    lda (src_ptr)\n    inc src_ptr\n    bne :+\n    inc src_ptr+1\n:   sta (dst_ptr)\n")
        decomp_end = 0x0200 + len(part1_sem)
        f.write("    inc dst_ptr\n    bne :+\n    inc dst_ptr+1\n:   ")
        f.write(f"lda dst_ptr\n    cmp #${decomp_end & 0xFF:02X}\n    bne :+\n    lda dst_ptr+1\n    cmp #${(decomp_end >> 8) & 0xFF:02X}\n    bne :+\n    jmp decomp_done\n:   ")
        f.write("dec gamma_val\n    bne @lit_loop\n")
        f.write("    lda gamma_val+1\n    beq :+\n    dec gamma_val+1\n    jmp @lit_loop\n:   jmp decomp_loop\n\n")

        f.write("@is_match:\n")
        f.write("    jsr get_bit\n")
        f.write("    bcs @rep_match\n\n")

        f.write("    ; New offset match\n")
        f.write("    jsr get_gamma\n")
        f.write("    lda gamma_val\n    sec\n    sbc #1\n    sta match_off+1\n")
        f.write("    lda (src_ptr)\n    inc src_ptr\n    bne :+\n    inc src_ptr+1\n:   sta match_off\n")
        f.write("    inc match_off\n    bne :+\n    inc match_off+1\n:   ")
        f.write("lda match_off\n    sta last_off\n    lda match_off+1\n    sta last_off+1\n")
        f.write("    jsr get_gamma\n    inc gamma_val\n    bne :+\n    inc gamma_val+1\n:   jmp @do_copy\n\n")

        f.write("@rep_match:\n")
        f.write("    lda last_off\n    sta match_off\n    lda last_off+1\n    sta match_off+1\n")
        f.write("    jsr get_gamma\n    inc gamma_val\n    bne :+\n    inc gamma_val+1\n:   \n\n")

        f.write("@do_copy:\n")
        f.write("    sec\n    lda dst_ptr\n    sbc match_off\n    sta copy_ptr\n")
        f.write("    lda dst_ptr+1\n    sbc match_off+1\n    sta copy_ptr+1\n")
        f.write("@copy_loop:\n")
        f.write("    lda (copy_ptr)\n    inc copy_ptr\n    bne :+\n    inc copy_ptr+1\n:   sta (dst_ptr)\n")
        f.write("    inc dst_ptr\n    bne :+\n    inc dst_ptr+1\n:   ")
        f.write(f"lda dst_ptr\n    cmp #${decomp_end & 0xFF:02X}\n    bne :+\n    lda dst_ptr+1\n    cmp #${(decomp_end >> 8) & 0xFF:02X}\n    bne :+\n    jmp decomp_done\n:   ")
        f.write("dec gamma_val\n    bne @copy_loop\n")
        f.write("    lda gamma_val+1\n    beq :+\n    dec gamma_val+1\n    jmp @copy_loop\n:   jmp decomp_loop\n\n")

        f.write("decomp_done:\n")
        f.write("    ; Start playback from RAM ($0200)\n")
        f.write("    lda #$00\n    sta play_ptr\n")
        f.write("    lda #$02\n    sta play_ptr+1\n")
        f.write("    stz ctrl_v1\n    stz ctrl_v2\n    stz ctrl_v3\n")
        f.write("    lda #$00\n    sta pw_v1\n    sta pw_v2\n    sta pw_v3\n")
        f.write("    lda #$08\n    sta pw_v1+1\n    sta pw_v2+1\n    sta pw_v3+1\n\n")

        f.write("play_loop:\n")
        f.write("    lda (play_ptr)\n    jsr advance_play_ptr\n")
        f.write("    cmp #$FF\n    bne :+\n    jmp stop_playback\n:   ")

        # Single register write 0x00 - 0x18
        f.write("cmp #$19\n    bcs check_note\n")
        f.write("    tax\n    lda (play_ptr)\n    jsr advance_play_ptr\n    sta $4800, x\n")
        f.write("    jmp play_loop\n\n")

        # Note trigger 0x19 - 0x1B
        f.write("check_note:\n")
        f.write("    cmp #$1C\n    bcs check_note_same\n")
        f.write("    sec\n    sbc #$19\n    sta temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n") # x = v * 7
        f.write("    lda (play_ptr)\n    jsr advance_play_ptr\n") # note
        f.write("    sec\n    sbc #ntbl_first_note\n    asl a\n    tay\n")
        f.write("    lda ntbl_table, y\n    sta $4800, x\n")
        f.write("    lda ntbl_table+1, y\n    sta $4801, x\n")
        f.write("    lda (play_ptr)\n    jsr advance_play_ptr\n    sta $4804, x\n") # ctrl
        f.write("    ldy temp_reg\n    sta ctrl_v1, y\n")
        f.write("    jmp play_loop\n\n")

        # Note same 0x1C - 0x1E
        f.write("check_note_same:\n")
        f.write("    cmp #$1F\n    bcs check_note_raw\n")
        f.write("    sec\n    sbc #$1C\n    sta temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    lda (play_ptr)\n    jsr advance_play_ptr\n")
        f.write("    sec\n    sbc #ntbl_first_note\n    asl a\n    tay\n")
        f.write("    lda ntbl_table, y\n    sta $4800, x\n")
        f.write("    lda ntbl_table+1, y\n    sta $4801, x\n")
        f.write("    ldy temp_reg\n    lda ctrl_v1, y\n    ora #$01\n    sta $4804, x\n    sta ctrl_v1, y\n")
        f.write("    jmp play_loop\n\n")

        # Note raw 0x1F - 0x21
        f.write("check_note_raw:\n")
        f.write("    cmp #$22\n    bcs check_gate_off\n")
        f.write("    sec\n    sbc #$1F\n    sta temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    lda (play_ptr)\n    jsr advance_play_ptr\n    sta $4800, x\n")
        f.write("    lda (play_ptr)\n    jsr advance_play_ptr\n    sta $4801, x\n")
        f.write("    lda (play_ptr)\n    jsr advance_play_ptr\n    sta $4804, x\n")
        f.write("    ldy temp_reg\n    sta ctrl_v1, y\n")
        f.write("    jmp play_loop\n\n")

        # Gate off 0x22 - 0x24
        f.write("check_gate_off:\n")
        f.write("    cmp #$25\n    bcs check_pw_up\n")
        f.write("    sec\n    sbc #$22\n    sta temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    ldy temp_reg\n    lda ctrl_v1, y\n    and #$FE\n    sta $4804, x\n    sta ctrl_v1, y\n")
        f.write("    jmp play_loop\n\n")

        # PW up 0x25 - 0x27
        f.write("check_pw_up:\n")
        f.write("    cmp #$28\n    bcs check_pw_dn\n")
        f.write("    sec\n    sbc #$25\n    sta temp_reg\n    asl a\n    tay\n")
        f.write("    clc\n    lda pw_v1, y\n    adc #<pw_step_val\n    sta pw_v1, y\n")
        f.write("    lda pw_v1+1, y\n    adc #>pw_step_val\n    sta pw_v1+1, y\n")
        f.write("    lda temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    lda pw_v1, y\n    sta $4802, x\n    lda pw_v1+1, y\n    sta $4803, x\n")
        f.write("    jmp play_loop\n\n")

        # PW dn 0x28 - 0x2A
        f.write("check_pw_dn:\n")
        f.write("    cmp #$2B\n    bcs check_pw_set\n")
        f.write("    sec\n    sbc #$28\n    sta temp_reg\n    asl a\n    tay\n")
        f.write("    sec\n    lda pw_v1, y\n    sbc #<pw_step_val\n    sta pw_v1, y\n")
        f.write("    lda pw_v1+1, y\n    sbc #>pw_step_val\n    sta pw_v1+1, y\n")
        f.write("    lda temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    lda pw_v1, y\n    sta $4802, x\n    lda pw_v1+1, y\n    sta $4803, x\n")
        f.write("    jmp play_loop\n\n")

        # PW set 0x2B - 0x2D
        f.write("check_pw_set:\n")
        f.write("    cmp #$2E\n    bcs check_freq_set\n")
        f.write("    sec\n    sbc #$2B\n    sta temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    lda temp_reg\n    asl a\n    tay\n")
        f.write("    lda (play_ptr)\n    jsr advance_play_ptr\n    sta $4802, x\n    sta pw_v1, y\n")
        f.write("    lda (play_ptr)\n    jsr advance_play_ptr\n    sta $4803, x\n    sta pw_v1+1, y\n")
        f.write("    jmp play_loop\n\n")

        # Freq set 0x2E - 0x30
        f.write("check_freq_set:\n")
        f.write("    cmp #$31\n    bcs check_freq_note\n")
        f.write("    sec\n    sbc #$2E\n    sta temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    lda (play_ptr)\n    jsr advance_play_ptr\n    sta $4800, x\n")
        f.write("    lda (play_ptr)\n    jsr advance_play_ptr\n    sta $4801, x\n")
        f.write("    jmp play_loop\n\n")

        # Freq note 0x31 - 0x33
        f.write("check_freq_note:\n")
        f.write("    cmp #$34\n    bcs check_delays\n")
        f.write("    sec\n    sbc #$31\n    sta temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    lda (play_ptr)\n    jsr advance_play_ptr\n")
        f.write("    sec\n    sbc #ntbl_first_note\n    asl a\n    tay\n")
        f.write("    lda ntbl_table, y\n    sta $4800, x\n")
        f.write("    lda ntbl_table+1, y\n    sta $4801, x\n")
        f.write("    jmp play_loop\n\n")

        # Delays: 0x34, 0x35, 0x80..0xFE
        f.write("check_delays:\n")
        f.write("    cmp #$34\n    bne @chk_dw\n")
        f.write("    lda (play_ptr)\n    jsr advance_play_ptr\n    sta delay_rem\n    stz delay_rem+1\n    jmp exec_delay\n")
        f.write("@chk_dw:\n")
        f.write("    cmp #$35\n    bne @chk_dict\n")
        f.write("    lda (play_ptr)\n    jsr advance_play_ptr\n    sta delay_rem\n")
        f.write("    lda (play_ptr)\n    jsr advance_play_ptr\n    sta delay_rem+1\n    jmp exec_delay\n")
        f.write("@chk_dict:\n")
        f.write("    sec\n    sbc #$80\n    asl a\n    tay\n")
        f.write("    lda dict_table, y\n    sta delay_rem\n    lda dict_table+1, y\n    sta delay_rem+1\n\n")

        f.write("exec_delay:\n")
        f.write("    ; Loop 15 cycles per unit\n")
        f.write("@d_loop:\n")
        f.write("    lda delay_rem\n    ora delay_rem+1\n    beq @d_done\n")
        f.write("    lda delay_rem\n    bne :+\n    dec delay_rem+1\n:   dec delay_rem\n")
        f.write("    nop\n    nop\n")
        f.write("    jmp @d_loop\n")
        f.write("@d_done:\n")
        f.write("    jmp play_loop\n\n")

        f.write("advance_play_ptr:\n")
        f.write("    inc play_ptr\n    bne :+\n    inc play_ptr+1\n:   ")
        if part2_sem:
            f.write("pha\n    ")
            f.write(f"lda play_ptr\n    cmp #${decomp_end & 0xFF:02X}\n    bne @adv_done\n")
            f.write(f"    lda play_ptr+1\n    cmp #${(decomp_end >> 8) & 0xFF:02X}\n    bne @adv_done\n")
            f.write("    lda #<part2_data\n    sta play_ptr\n    lda #>part2_data\n    sta play_ptr+1\n")
            f.write("@adv_done:\n    pla\n")
        f.write("    rts\n\n")

        f.write("stop_playback:\n")
        f.write("    lda #0\n    sta $4804\n    sta $480B\n    sta $4812\n    stp\n\n")

        # Helper subroutines for decompressor
        f.write("get_bit:\n")
        f.write("    asl bit_buf\n    bne @ok\n")
        f.write("    lda (src_ptr)\n    inc src_ptr\n    bne :+\n    inc src_ptr+1\n:   rol a\n    sta bit_buf\n")
        f.write("@ok:\n    rts\n\n")

        f.write("get_gamma:\n")
        f.write("    stz zeros_cnt\n")
        f.write("@loop_zeros:\n")
        f.write("    jsr get_bit\n    bcs @got_zeros\n    inc zeros_cnt\n    jmp @loop_zeros\n")
        f.write("@got_zeros:\n")
        f.write("    lda #1\n    sta gamma_val\n    stz gamma_val+1\n    ldx zeros_cnt\n    beq @done\n")
        f.write("@shift_bits:\n")
        f.write("    jsr get_bit\n    rol gamma_val\n    rol gamma_val+1\n    dex\n    bne @shift_bits\n")
        f.write("@done:\n    rts\n\n")

        # Tables
        f.write(f"ntbl_first_note = {ntbl_first}\n")
        f.write(f"pw_step_val = {pw_step}\n\n")

        f.write("ntbl_table:\n")
        for fv in ntbl:
            f.write(f"    .word ${fv:04X}\n")

        f.write("\ndict_table:\n")
        for dv in dict_delays:
            f.write(f"    .word ${dv:04X}\n")

        f.write("\ncompressed_stream:\n")
        chunk_size = 16
        for i in range(0, len(pkg), chunk_size):
            chunk = pkg[i:i + chunk_size]
            hex_str = ", ".join([f"${b:02X}" for b in chunk])
            f.write(f"    .byte {hex_str}\n")

        if part2_sem:
            f.write("\npart2_data:\n")
            for i in range(0, len(part2_sem), chunk_size):
                chunk = part2_sem[i:i + chunk_size]
                hex_str = ", ".join([f"${b:02X}" for b in chunk])
                f.write(f"    .byte {hex_str}\n")

        f.write("\n.segment \"VECTORS\"\n")
        f.write("    .word reset\n    .word reset\n    .word reset\n")

    size_bytes = len(pkg) + len(part2_sem)
    print(f"Generated {output_file}")
    print(f"Bytecode: {size_bytes} bytes ({size_bytes / 1024.0:.1f} KB)")

    _compile_and_report(output_file, limit_bytes=32768)
    return output_file


def _compile_and_report(asm_file, limit_bytes):
    name = os.path.splitext(os.path.basename(asm_file))[0]
    build_dir = os.path.dirname(asm_file)
    obj_file = os.path.join(build_dir, name + ".o")
    bin_file = os.path.join(build_dir, name + ".bin")

    project_root = os.path.dirname(os.path.dirname(_SCRIPT_DIR))
    linker_cfg = os.path.join(project_root, "sdk", "linker", "raw.cfg")

    r = subprocess.run(
        ["ca65", "--cpu", "65C02", "-o", obj_file, asm_file],
        capture_output=True, text=True
    )
    if r.returncode != 0:
        print(">> [ca65 ERROR] Assembly failed:")
        print(r.stderr.strip())
        return

    r = subprocess.run(
        ["ld65", "-C", linker_cfg, "-o", bin_file, obj_file],
        capture_output=True, text=True
    )
    if r.returncode != 0:
        print(f">> WARNING: Linking FAILED — likely exceeds {limit_bytes // 1024}KB limit")
        if r.stderr:
            print(r.stderr.strip())
        return

    bin_size = os.path.getsize(bin_file)
    bin_kb = bin_size / 1024.0
    percent = (bin_size / limit_bytes) * 100.0
    limit_kb = limit_bytes // 1024

    print(f"Binary:   {bin_size} bytes ({bin_kb:.1f} KB) — {percent:.1f}% of {limit_kb}KB")
    if bin_size > limit_bytes:
        excess = bin_size - limit_bytes
        print(f">> WARNING: FILE EXCEEDS 32KB LIMIT by {excess} bytes!")
    else:
        free = limit_bytes - bin_size
        print(f">> OK: Fits in 32KB. ({free} bytes free)")
