import os
import subprocess
import sys

_SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
if _SCRIPT_DIR not in sys.path:
    sys.path.insert(0, _SCRIPT_DIR)

from sid_codec import encode_semantic_v2, decode_semantic_v2, compress_sidlz, decompress_sidlz


def calculate_duration(bytecode, system="NTSC"):
    clock_freq = 1000000.0 if system == "NTSC" else 985248.0
    total_cycles = 0.0
    i = 0
    n = len(bytecode)
    while i < n:
        cmd = bytecode[i]
        i += 1
        if cmd == 0xFF:
            break
        elif cmd == 0x82:
            if i < n:
                total_cycles += bytecode[i] * 15.0
                i += 1
        elif cmd == 0x81:
            if i + 1 < n:
                total_cycles += (bytecode[i] | (bytecode[i + 1] << 8)) * 15.0
                i += 2
        elif 0x90 <= cmd <= 0x92:
            i += 3
        elif 0x93 <= cmd <= 0x95:
            pass
        elif cmd <= 0x18:
            i += 1
        else:
            i += 1
    total_sec = total_cycles / clock_freq
    mins = int(total_sec // 60)
    secs = int(total_sec % 60)
    return mins, secs, total_sec


def write_asm(bytecode, input_path, mode, system="NTSC", verify=True):
    filename_only = os.path.splitext(os.path.basename(input_path))[0].replace(" ", "") + ".s"
    output_dir = os.path.join(_SCRIPT_DIR, "build")
    if not os.path.exists(output_dir):
        os.makedirs(output_dir)
    output_file = os.path.join(output_dir, filename_only)

    print(f"Writing streaming compressed Native ASM to {output_file}...")

    hdr, sem = encode_semantic_v2(bytecode)
    pkg = compress_sidlz(sem, window_size=2048)

    if verify:
        sem_rec = decompress_sidlz(pkg, expected_uncompressed_len=len(sem))
        assert sem_rec == sem, "Semantic stream mismatch in SIDLZ roundtrip"
        ir_rec = decode_semantic_v2(hdr, sem_rec)
        assert ir_rec == bytecode, "Lossless IR mismatch in SIDLZ roundtrip"

    ntbl_first = hdr['ntbl_first']
    ntbl = hdr['ntbl']
    dict_delays = hdr['dict']
    pw_step = hdr['pw_step']

    mins, secs, total_sec = calculate_duration(bytecode, system)
    dur_str = f"{mins}:{secs:02d}"

    with open(output_file, "w") as f:
        f.write(f"; Generated by audio_to_sid.py (Mode: {mode}, System: {system})\n")
        f.write("; Native 65C02 SIDLZ Streaming ROM Player (2KB Ring Window in RAM)\n\n")

        f.write(".segment \"ZEROPAGE\"\n")
        f.write("src_ptr:     .res 2\n")
        f.write("win_idx:     .res 2\n")
        f.write("win_ptr:     .res 2\n")
        f.write("copy_ptr:    .res 2\n")
        f.write("bit_buf:     .res 1\n")
        f.write("decomp_mode: .res 1\n")
        f.write("decomp_rem:  .res 2\n")
        f.write("gamma_val:   .res 2\n")
        f.write("zeros_cnt:   .res 1\n")
        f.write("last_off:    .res 2\n")
        f.write("match_off:   .res 2\n")
        f.write("delay_rem:   .res 2\n")
        f.write("temp_reg:    .res 2\n")
        f.write("ctrl_v1:     .res 1\n")
        f.write("ctrl_v2:     .res 1\n")
        f.write("ctrl_v3:     .res 1\n")
        f.write("pw_v1:       .res 2\n")
        f.write("pw_v2:       .res 2\n")
        f.write("pw_v3:       .res 2\n")

        f.write("\n.segment \"CODE\"\n")
        f.write("reset:\n")
        f.write("    ldx #$FF\n    txs\n    cld\n    sei\n\n")

        f.write("    ; Reset SID registers\n")
        f.write("    ldx #$18\n    lda #0\n:   sta $4800, x\n    dex\n    bpl :-\n\n")

        f.write("    ; Init VIA Timer 1 ($6000)\n")
        f.write("    lda #$00\n    sta $600B\n")
        f.write("    lda #$FF\n    sta $6004\n    sta $6005\n    sta $6006\n    sta $6007\n\n")

        f.write("    ; Init streaming decompressor (window at $0200..$09FF)\n")
        f.write("    lda #<compressed_stream\n    sta src_ptr\n")
        f.write("    lda #>compressed_stream\n    sta src_ptr+1\n")
        f.write("    stz win_idx\n    stz win_idx+1\n")
        f.write("    stz decomp_rem\n    stz decomp_rem+1\n")
        f.write("    stz decomp_mode\n")
        f.write("    lda #$80\n    sta bit_buf\n")
        f.write("    stz last_off\n    stz last_off+1\n\n")

        f.write("    ; Init player shadow registers\n")
        f.write("    stz ctrl_v1\n    stz ctrl_v2\n    stz ctrl_v3\n")
        f.write("    lda #$00\n    sta pw_v1\n    sta pw_v2\n    sta pw_v3\n")
        f.write("    lda #$08\n    sta pw_v1+1\n    sta pw_v2+1\n    sta pw_v3+1\n\n")

        f.write("play_loop:\n")
        f.write("    jsr get_next_sem_byte\n")
        f.write("    cmp #$FF\n    bne :+\n    jmp stop_playback\n:   ")

        f.write("cmp #$19\n    bcs check_note\n")
        f.write("    tax\n    jsr get_next_sem_byte\n    sta $4800, x\n")
        f.write("    jmp play_loop\n\n")

        f.write("check_note:\n")
        f.write("    cmp #$1C\n    bcs check_note_same\n")
        f.write("    sec\n    sbc #$19\n    sta temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    jsr get_next_sem_byte\n")
        f.write("    sec\n    sbc #ntbl_first_note\n    asl a\n    tay\n")
        f.write("    lda ntbl_table, y\n    sta $4800, x\n")
        f.write("    lda ntbl_table+1, y\n    sta $4801, x\n")
        f.write("    jsr get_next_sem_byte\n    sta $4804, x\n")
        f.write("    ldy temp_reg\n    sta ctrl_v1, y\n")
        f.write("    jmp play_loop\n\n")

        f.write("check_note_same:\n")
        f.write("    cmp #$1F\n    bcs check_note_raw\n")
        f.write("    sec\n    sbc #$1C\n    sta temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    jsr get_next_sem_byte\n")
        f.write("    sec\n    sbc #ntbl_first_note\n    asl a\n    tay\n")
        f.write("    lda ntbl_table, y\n    sta $4800, x\n")
        f.write("    lda ntbl_table+1, y\n    sta $4801, x\n")
        f.write("    ldy temp_reg\n    lda ctrl_v1, y\n    ora #$01\n    sta $4804, x\n    sta ctrl_v1, y\n")
        f.write("    jmp play_loop\n\n")

        f.write("check_note_raw:\n")
        f.write("    cmp #$22\n    bcs check_gate_off\n")
        f.write("    sec\n    sbc #$1F\n    sta temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    jsr get_next_sem_byte\n    sta $4800, x\n")
        f.write("    jsr get_next_sem_byte\n    sta $4801, x\n")
        f.write("    jsr get_next_sem_byte\n    sta $4804, x\n")
        f.write("    ldy temp_reg\n    sta ctrl_v1, y\n")
        f.write("    jmp play_loop\n\n")

        f.write("check_gate_off:\n")
        f.write("    cmp #$25\n    bcs check_pw_up\n")
        f.write("    sec\n    sbc #$22\n    sta temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    ldy temp_reg\n    lda ctrl_v1, y\n    and #$FE\n    sta $4804, x\n    sta ctrl_v1, y\n")
        f.write("    jmp play_loop\n\n")

        f.write("check_pw_up:\n")
        f.write("    cmp #$28\n    bcs check_pw_dn\n")
        f.write("    sec\n    sbc #$25\n    sta temp_reg\n    asl a\n    tay\n")
        f.write("    clc\n    lda pw_v1, y\n    adc #<pw_step_val\n    sta pw_v1, y\n")
        f.write("    lda pw_v1+1, y\n    adc #>pw_step_val\n    sta pw_v1+1, y\n")
        f.write("    lda temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    lda pw_v1, y\n    sta $4802, x\n    lda pw_v1+1, y\n    sta $4803, x\n")
        f.write("    jmp play_loop\n\n")

        f.write("check_pw_dn:\n")
        f.write("    cmp #$2B\n    bcs check_pw_set\n")
        f.write("    sec\n    sbc #$28\n    sta temp_reg\n    asl a\n    tay\n")
        f.write("    sec\n    lda pw_v1, y\n    sbc #<pw_step_val\n    sta pw_v1, y\n")
        f.write("    lda pw_v1+1, y\n    sbc #>pw_step_val\n    sta pw_v1+1, y\n")
        f.write("    lda temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    lda pw_v1, y\n    sta $4802, x\n    lda pw_v1+1, y\n    sta $4803, x\n")
        f.write("    jmp play_loop\n\n")

        f.write("check_pw_set:\n")
        f.write("    cmp #$2E\n    bcs check_freq_set\n")
        f.write("    sec\n    sbc #$2B\n    sta temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    lda temp_reg\n    asl a\n    tay\n")
        f.write("    jsr get_next_sem_byte\n    sta $4802, x\n    sta pw_v1, y\n")
        f.write("    jsr get_next_sem_byte\n    sta $4803, x\n    sta pw_v1+1, y\n")
        f.write("    jmp play_loop\n\n")

        f.write("check_freq_set:\n")
        f.write("    cmp #$31\n    bcs check_freq_note\n")
        f.write("    sec\n    sbc #$2E\n    sta temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    jsr get_next_sem_byte\n    sta $4800, x\n")
        f.write("    jsr get_next_sem_byte\n    sta $4801, x\n")
        f.write("    jmp play_loop\n\n")

        f.write("check_freq_note:\n")
        f.write("    cmp #$34\n    bcs check_delays\n")
        f.write("    sec\n    sbc #$31\n    sta temp_reg\n    asl a\n    asl a\n    asl a\n    sec\n    sbc temp_reg\n    tax\n")
        f.write("    jsr get_next_sem_byte\n")
        f.write("    sec\n    sbc #ntbl_first_note\n    asl a\n    tay\n")
        f.write("    lda ntbl_table, y\n    sta $4800, x\n")
        f.write("    lda ntbl_table+1, y\n    sta $4801, x\n")
        f.write("    jmp play_loop\n\n")

        f.write("check_delays:\n")
        f.write("    cmp #$34\n    bne @chk_dw\n")
        f.write("    jsr get_next_sem_byte\n    tax\n    ldy #0\n    jmp exec_delay\n")
        f.write("@chk_dw:\n")
        f.write("    cmp #$35\n    bne @chk_dict\n")
        f.write("    jsr get_next_sem_byte\n    tax\n")
        f.write("    jsr get_next_sem_byte\n    tay\n    jmp exec_delay\n")
        f.write("@chk_dict:\n")
        f.write("    sec\n    sbc #$80\n    tax\n")
        f.write("    lda dict_table_hi, x\n    tay\n    lda dict_table_lo, x\n    tax\n\n")

        f.write("exec_delay:\n")
        f.write("    ; Calibrated exact 15 cycles per unit\n")
        f.write("@d_loop:\n")
        f.write("    cpx #0\n    bne :+\n    cpy #0\n    beq @d_done\n    dey\n:   dex\n    nop\n    lda delay_rem\n    jmp @d_loop\n")
        f.write("@d_done:\n")
        f.write("    jmp play_loop\n\n")

        f.write("stop_playback:\n")
        f.write("    lda #0\n    sta $4804\n    sta $480B\n    sta $4812\n    stp\n\n")

        f.write("get_next_sem_byte:\n")
        f.write("    phx\n    phy\n\n")
        f.write("    lda decomp_rem\n    ora decomp_rem+1\n    bne @have_mode\n\n")
        f.write("    jsr get_bit\n    bcs @is_match\n\n")
        f.write("    ; Literal run: length = get_gamma()\n")
        f.write("    jsr get_gamma\n")
        f.write("    lda gamma_val\n    sta decomp_rem\n")
        f.write("    lda gamma_val+1\n    sta decomp_rem+1\n")
        f.write("    lda #1\n    sta decomp_mode\n")
        f.write("    jmp @do_literal\n\n")
        f.write("@is_match:\n")
        f.write("    jsr get_bit\n    bcs @rep_match\n\n")
        f.write("    ; New offset match: off_hi = get_gamma() - 1, off_lo = next_byte()\n")
        f.write("    jsr get_gamma\n")
        f.write("    lda gamma_val\n    sec\n    sbc #1\n    sta match_off+1\n")
        f.write("    lda (src_ptr)\n    inc src_ptr\n    bne :+\n    inc src_ptr+1\n:   sta match_off\n")
        f.write("    inc match_off\n    bne :+\n    inc match_off+1\n:   ")
        f.write("lda match_off\n    sta last_off\n    lda match_off+1\n    sta last_off+1\n")
        f.write("    jsr get_gamma\n    inc gamma_val\n    bne :+\n    inc gamma_val+1\n:   ")
        f.write("lda gamma_val\n    sta decomp_rem\n    lda gamma_val+1\n    sta decomp_rem+1\n")
        f.write("    lda #2\n    sta decomp_mode\n    jmp @do_match\n\n")
        f.write("@rep_match:\n")
        f.write("    lda last_off\n    sta match_off\n    lda last_off+1\n    sta match_off+1\n")
        f.write("    jsr get_gamma\n    inc gamma_val\n    bne :+\n    inc gamma_val+1\n:   ")
        f.write("lda gamma_val\n    sta decomp_rem\n    lda gamma_val+1\n    sta decomp_rem+1\n")
        f.write("    lda #2\n    sta decomp_mode\n    jmp @do_match\n\n")
        f.write("@have_mode:\n")
        f.write("    lda decomp_mode\n    cmp #1\n    beq @do_literal\n\n")
        f.write("@do_match:\n")
        f.write("    sec\n    lda win_idx\n    sbc match_off\n    sta copy_ptr\n")
        f.write("    lda win_idx+1\n    sbc match_off+1\n    and #$07\n    clc\n    adc #$02\n    sta copy_ptr+1\n")
        f.write("    lda (copy_ptr)\n    pha\n")
        f.write("    jsr write_win_byte\n    jsr dec_decomp_rem\n")
        f.write("    pla\n    ply\n    plx\n    rts\n\n")
        f.write("@do_literal:\n")
        f.write("    lda (src_ptr)\n    inc src_ptr\n    bne :+\n    inc src_ptr+1\n:   pha\n")
        f.write("    jsr write_win_byte\n    jsr dec_decomp_rem\n")
        f.write("    pla\n    ply\n    plx\n    rts\n\n")

        f.write("write_win_byte:\n")
        f.write("    pha\n    lda win_idx+1\n    clc\n    adc #$02\n    sta win_ptr+1\n")
        f.write("    lda win_idx\n    sta win_ptr\n    pla\n    sta (win_ptr)\n")
        f.write("    inc win_idx\n    bne :+\n    inc win_idx+1\n    lda win_idx+1\n    and #$07\n    sta win_idx+1\n:   rts\n\n")

        f.write("dec_decomp_rem:\n")
        f.write("    lda decomp_rem\n    bne :+\n    dec decomp_rem+1\n:   dec decomp_rem\n    rts\n\n")

        f.write("get_bit:\n")
        f.write("    asl bit_buf\n    bne @bit_ok\n")
        f.write("    lda (src_ptr)\n    inc src_ptr\n    bne :+\n    inc src_ptr+1\n:   rol a\n    sta bit_buf\n")
        f.write("@bit_ok:\n    rts\n\n")

        f.write("get_gamma:\n")
        f.write("    stz zeros_cnt\n")
        f.write("@loop_zeros:\n")
        f.write("    jsr get_bit\n    bcs @got_zeros\n    inc zeros_cnt\n    jmp @loop_zeros\n")
        f.write("@got_zeros:\n")
        f.write("    lda #1\n    sta gamma_val\n    stz gamma_val+1\n    ldx zeros_cnt\n    beq @gamma_done\n")
        f.write("@shift_bits:\n")
        f.write("    jsr get_bit\n    rol gamma_val\n    rol gamma_val+1\n    dex\n    bne @shift_bits\n")
        f.write("@gamma_done:\n    rts\n\n")

        f.write(f"ntbl_first_note = {ntbl_first}\n")
        f.write(f"pw_step_val = {pw_step}\n\n")

        f.write("ntbl_table:\n")
        for fv in ntbl:
            f.write(f"    .word ${fv:04X}\n")

        f.write("\ndict_table_lo:\n")
        for dv in dict_delays:
            f.write(f"    .byte ${dv & 0xFF:02X}\n")

        f.write("\ndict_table_hi:\n")
        for dv in dict_delays:
            f.write(f"    .byte ${(dv >> 8) & 0xFF:02X}\n")

        f.write("\ncompressed_stream:\n")
        chunk_size = 16
        for i in range(0, len(pkg), chunk_size):
            chunk = pkg[i:i + chunk_size]
            hex_str = ", ".join([f"${b:02X}" for b in chunk])
            f.write(f"    .byte {hex_str}\n")

        f.write("\n.segment \"VECTORS\"\n")
        f.write("    .word reset\n    .word reset\n    .word reset\n")

    ir_size = len(bytecode)
    sem_size = len(sem)
    pkg_size = len(pkg)
    ratio = (pkg_size / ir_size * 100.0) if ir_size > 0 else 0

    print(f"Generated {output_file}")
    print(f"Song Duration:   {dur_str} ({total_sec:.1f}s)")
    print(f"IR bytecode:     {ir_size} bytes ({ir_size / 1024.0:.1f} KB)")
    print(f"Semantic stream: {sem_size} bytes ({sem_size / 1024.0:.1f} KB)")
    print(f"Compressed pkg:  {pkg_size} bytes ({pkg_size / 1024.0:.1f} KB) — {ratio:.1f}% of IR ({100.0 - ratio:.1f}% reduction)")

    fits, bin_size = _compile_and_report(output_file, limit_bytes=32768)
    return output_file, fits


def _compile_and_report(asm_file, limit_bytes):
    name = os.path.splitext(os.path.basename(asm_file))[0]
    build_dir = os.path.dirname(asm_file)
    obj_file = os.path.join(build_dir, name + ".o")
    bin_file = os.path.join(build_dir, name + ".bin")

    project_root = os.path.dirname(os.path.dirname(_SCRIPT_DIR))
    linker_cfg = os.path.join(project_root, "sdk", "linker", "raw.cfg")

    r = subprocess.run(
        ["ca65", "--cpu", "65C02", "-o", obj_file, asm_file],
        capture_output=True, text=True
    )
    if r.returncode != 0:
        print(">> [ca65 ERROR] Assembly failed:")
        print(r.stderr.strip())
        return False, 0

    map_file = os.path.join(build_dir, name + ".map")
    r = subprocess.run(
        ["ld65", "-C", linker_cfg, "-m", map_file, "-o", bin_file, obj_file],
        capture_output=True, text=True
    )
    if r.returncode != 0:
        print(f">> WARNING: Linking FAILED — likely exceeds {limit_bytes // 1024}KB limit")
        if r.stderr:
            print(r.stderr.strip())
        return False, 0

    bin_size = os.path.getsize(bin_file)
    bin_kb = bin_size / 1024.0
    limit_kb = limit_bytes // 1024

    actual_used = 0
    if os.path.exists(map_file):
        with open(map_file, "r") as mf:
            for line in mf:
                parts = line.split()
                if len(parts) >= 4 and parts[0] in ("CODE", "RODATA", "DATA", "VECTORS"):
                    for p in parts:
                        if p.startswith("Size="):
                            try:
                                actual_used += int(p.split("=")[1], 16)
                            except ValueError:
                                pass

    if actual_used > 0:
        used_kb = actual_used / 1024.0
        used_pct = (actual_used / limit_bytes) * 100.0
        free_bytes = limit_bytes - actual_used
        free_kb = free_bytes / 1024.0
        print(f"ROM Payload:     {actual_used} bytes ({used_kb:.1f} KB) — {used_pct:.1f}% of {limit_kb}KB ROM ({free_bytes} B / {free_kb:.1f} KB free)")
        print(f"ROM File (fill): {bin_size} bytes ({bin_kb:.1f} KB) — padded to $FFFF")
    else:
        percent = (bin_size / limit_bytes) * 100.0
        print(f"ROM Binary:      {bin_size} bytes ({bin_kb:.1f} KB) — {percent:.1f}% of {limit_kb}KB ROM")

    print("RAM Footprint:   2048 B sliding window ($0200..$09FF) + 30 ZP bytes (hardware MMIO safe)")
    if bin_size > limit_bytes or (actual_used > limit_bytes):
        excess = max(bin_size, actual_used) - limit_bytes
        print(f">> WARNING: FILE EXCEEDS 32KB LIMIT by {excess} bytes!")
        return False, bin_size
    else:
        return True, bin_size
